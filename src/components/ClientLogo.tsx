export default function ClientLogo({
  client,
  className,
}: {
  client: string;
  className?: string;
}) {
  const path = shapes[client] ?? paths[client];

  if (!path) {
    const words = client.split(" ");
    const isAcronym = words.length === 1 && client === client.toUpperCase();
    const initials =
      words.length > 1
        ? words.map((w) => w[0]).join("").slice(0, 3)
        : isAcronym
          ? client.slice(0, 3)
          : client[0].toUpperCase();
    return (
      <span
        className={`font-display flex items-center justify-center border-2 border-current text-[0.6rem] font-bold leading-none ${className}`}
      >
        {initials}
      </span>
    );
  }

  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      className={className}
      aria-hidden="true"
    >
      <path d={path} />
    </svg>
  );
}
